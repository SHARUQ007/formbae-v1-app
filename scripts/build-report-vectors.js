// Keep the editable SVG originals and the native runtime catalogue in sync.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const directory = path.join(root, 'src/assets/report-vectors');
const catalog = {};
for (const file of fs.readdirSync(directory).filter(name => name.endsWith('.svg')).sort()) {
  const kind = file.replace(/-\d+\.svg$/, '');
  (catalog[kind] ||= []).push(fs.readFileSync(path.join(directory, file), 'utf8').trim());
}
const output = `// Generated by scripts/build-report-vectors.js from editable SVG originals.\nexport const REPORT_ILLUSTRATIONS = ${JSON.stringify(catalog, null, 2)} as const;\nexport type ReportIllustrationKind = keyof typeof REPORT_ILLUSTRATIONS;\n`;
fs.writeFileSync(path.join(root, 'src/utils/reportIllustrationCatalog.ts'), output);
console.log(`Built ${Object.values(catalog).flat().length} report illustrations.`);
